// Public-only enhancement. No network, storage, analytics, uploads or account actions.
function initializeLanding() {
    const root = document.querySelector(".lc-public");
    if (!root || root.dataset.enhanced) return;
    root.dataset.enhanced = "true";
    root.querySelectorAll("[data-faq-toggle]").forEach(button => {
        button.addEventListener("click", () => {
            const expanded = button.getAttribute("aria-expanded") === "true";
            button.setAttribute("aria-expanded", String(!expanded));
            document.getElementById(button.getAttribute("aria-controls")).hidden = expanded;
            button.querySelector("span").textContent = expanded ? "+" : "−";
        });
    });
    const demo = root.querySelector("[data-landing-demo]");
    if (demo) {
        demo.querySelector("[data-demo-name]").addEventListener("input", event => {
            demo.querySelector("[data-demo-title]").textContent = event.target.value.trim() || "TU NEGOCIO";
        });
        demo.querySelector("[data-demo-color]").addEventListener("change", event => {
            const option = event.target.selectedOptions[0];
            const card = demo.querySelector("[data-demo-card]");
            // Foreground is generated by the existing WalletColorContrast C# helper.
            card.style.setProperty("--demo-bg", option.value);
            card.style.setProperty("--demo-fg", option.dataset.foreground);
            demo.querySelector(".lp-demo-result").style.background =
                "color-mix(in srgb, " + option.value + " 15%, #f3f5ee)";
        });
    }
    const industries = root.querySelector("[data-industry-section]");
    if (industries) industries.querySelectorAll("[data-industry]").forEach(button => {
        button.addEventListener("click", () => {
            industries.querySelectorAll("[data-industry]").forEach(item =>
                item.setAttribute("aria-pressed", String(item === button)));
            industries.querySelector("[data-industry-label]").textContent = button.dataset.industry;
            industries.querySelector("[data-industry-copy]").textContent = button.dataset.copy;
            industries.querySelector("[data-industry-reward]").textContent = button.dataset.reward;
            industries.querySelector("[data-industry-program]").textContent = button.dataset.program;
        });
    });
    root.querySelectorAll(".lp-mobile-nav a").forEach(link => link.addEventListener("click", () => {
        const menu = link.closest("details");
        menu.open = false;
        const target = link.hash && document.getElementById(link.hash.slice(1));
        if (target) { target.setAttribute("tabindex", "-1"); target.focus({ preventScroll: true }); }
    }));
}
initializeLanding();
document.addEventListener("enhancedload", initializeLanding);
if (window.Blazor) window.Blazor.addEventListener("enhancedload", initializeLanding);
